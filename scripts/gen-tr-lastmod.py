#!/usr/bin/env python3
"""Writes src/content/tr-lastmod.ts: last content change per Turkish URL, for the sitemap <lastmod>.

Date = last git commit touching the page's route file (or, for data pages, its entry in
src/content/tr-pages.ts). Uncommitted edits count as today. Run before committing TR page changes:
  npm run sitemap:lastmod
"""
import datetime, pathlib, re, subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent
TODAY = datetime.date.today().isoformat()
SITEMAPS = (ROOT / "src/lib/sitemaps.ts").read_text()
TR_BLOCK = SITEMAPS.split("const TR:", 1)[1].split("];", 1)[0]
PATHS = re.findall(r'\["(/[^"]*)"', TR_BLOCK)
DATA = (ROOT / "src/content/tr-pages.ts").read_text()


def git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True).stdout.strip()


def changed_uncommitted(rel: str) -> bool:
    return bool(git("status", "--porcelain", "--", rel))


def route_date(path: str) -> str | None:
    rel = "src/app/(tr)" + ("/page.tsx" if path == "/" else f"{path}/page.tsx")
    if not (ROOT / rel).exists():
        return None
    if changed_uncommitted(rel):
        return TODAY
    return git("log", "-1", "--format=%cs", "--", rel) or None


def data_entry_date(path: str) -> str | None:
    start = DATA.find(f'  "{path}": {{')
    if start < 0:
        return None
    first = DATA.count("\n", 0, start) + 1
    end = DATA.find("\n  },\n", start)
    last = DATA.count("\n", 0, end) + 2
    rel = "src/content/tr-pages.ts"
    if changed_uncommitted(rel):
        diff = git("diff", "-U0", "HEAD", "--", rel)
        for m in re.finditer(r"^@@ -\d+(?:,\d+)? \+(\d+)(?:,(\d+))? @@", diff, re.M):
            a, n = int(m.group(1)), int(m.group(2) or 1)
            if a <= last and a + max(n, 1) - 1 >= first:
                return TODAY
    # Committed history of the entry's own line range.
    out = git("log", "-1", "--format=%cs", "-L", f"{first},{last}:{rel}")
    return out.splitlines()[0] if out else None


dates = {}
for p in PATHS:
    d = data_entry_date(p) if f'  "{p}": {{' in DATA else None
    r = route_date(p)
    # Data pages: the route file is a thin wrapper, so the entry date wins.
    dates[p] = d or r

lines = [
    "// Generated by scripts/gen-tr-lastmod.py (npm run sitemap:lastmod). Do not edit by hand.",
    "/** Last content change per Turkish URL (sitemap <lastmod>). */",
    "export const TR_LASTMOD: Record<string, string> = {",
    *[f'  "{p}": "{d}",' for p, d in dates.items() if d],
    "};",
    "",
]
(ROOT / "src/content/tr-lastmod.ts").write_text("\n".join(lines))
print(f"tr-lastmod: {sum(1 for d in dates.values() if d)}/{len(dates)} dated")
